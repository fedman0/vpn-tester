tasks.named("preBuild") {
    val coreLibs = listOf("arm64-v8a", "armeabi-v7a", "x86_64").map {
        layout.projectDirectory.file("src/main/jniLibs/$it/libcore.so").asFile
    }
    doFirst {
        val missing = coreLibs.filterNot { it.exists() }
        if (missing.isNotEmpty()) {
            throw GradleException("Test core is missing: ${missing.joinToString { it.parentFile.name }}. Run core/build.sh (needs Go) first.")
        }
    }
}
